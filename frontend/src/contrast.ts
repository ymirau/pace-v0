// WCAG relative-luminance / contrast-ratio math for the contrast tests. Lives
// outside any test file so more than one suite can share it; pure and DOM-free, so it runs under the default node env.

/** WCAG AA minimum contrast ratio for normal-size body text. */
export const AA = 4.5;

function channel(c: number): number {
  const s = c / 255;
  return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

function luminance(hex: string): number {
  const h = hex.replace("#", "");
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

/** Contrast ratio between two #rrggbb colours, 1:1 to 21:1. Order-independent. */
export function contrast(fg: string, bg: string): number {
  const [hi, lo] = [luminance(fg), luminance(bg)].sort((a, b) => b - a);
  return (hi + 0.05) / (lo + 0.05);
}
